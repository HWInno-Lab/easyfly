"""Replay recorded image/IMU messages into the actual installed OpenVINS node.

Observes estimator output and orderly shutdown. Does not initialize from truth,
publish flight commands or certify accuracy; evaluation against truth is separate.
"""

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import signal
import subprocess
import time

from geometry_msgs.msg import PoseWithCovarianceStamped
import rclpy


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--installation', required=True, type=Path)
    parser.add_argument('--config', required=True, type=Path)
    parser.add_argument('--bag', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--rate', type=float, default=.5)
    parser.add_argument('--camera-topic', default='/camera/color/image_raw')
    parser.add_argument('--imu-topic', default='/livox/imu')
    args = parser.parse_args()
    if not .1 <= args.rate <= 1:
        parser.error('rate must be in [.1, 1]')
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=False)
    installation = args.installation.resolve(strict=True)
    config = args.config.resolve(strict=True)
    bag = args.bag.resolve(strict=True)
    os.environ.update(ROS_LOCALHOST_ONLY='1', ROS_DOMAIN_ID='227',
                      ROS_LOG_DIR=str(out / 'ros'))
    executable = installation / 'ov_msckf/lib/ov_msckf/run_subscribe_msckf'
    record = dict(scope=__doc__.strip(), error=None, forced=False, rate=args.rate,
                  config=str(config), bag=str(bag), executable=str(executable),
                  files_sha256={str(p): hashlib.sha256(p.read_bytes()).hexdigest()
                                for p in [executable, *sorted(config.parent.glob('*.yaml')),
                                          bag / 'metadata.yaml']})
    estimator, player, node = None, None, None
    samples = []
    try:
        rclpy.init()
        node = rclpy.create_node('openvins_bag_observer')

        def receive(msg):
            p, q = msg.pose.pose.position, msg.pose.pose.orientation
            samples.append(dict(stamp_ns=msg.header.stamp.sec * 10**9 + msg.header.stamp.nanosec,
                                receipt=time.monotonic(), frame=msg.header.frame_id,
                                position=[p.x, p.y, p.z], quaternion=[q.x, q.y, q.z, q.w],
                                covariance=list(msg.pose.covariance)))

        subscription = node.create_subscription(  # noqa: F841 - keep subscription alive
            PoseWithCovarianceStamped, '/openvins_bag_probe/poseimu', receive, 100)
        command = [str(executable), str(config), '--ros-args', '-p', 'use_sim_time:=true',
                   '-p', 'publish_global_to_imu_tf:=false',
                   '-p', 'publish_calibration_tf:=false', '-r', '__ns:=/openvins_bag_probe']
        record['estimator_command'] = command
        with (out / 'estimator.log').open('w') as estimator_log, \
                (out / 'player.log').open('w') as player_log:
            estimator = subprocess.Popen(command, stdout=estimator_log, stderr=subprocess.STDOUT)
            deadline = time.monotonic() + 15
            while time.monotonic() < deadline:
                if estimator.poll() is not None:
                    raise RuntimeError('estimator exited before replay')
                rclpy.spin_once(node, timeout_sec=.02)
                if ('run_subscribe_msckf', '/openvins_bag_probe') not in \
                        node.get_node_names_and_namespaces():
                    continue
                subscriptions = dict(node.get_subscriber_names_and_types_by_node(
                    'run_subscribe_msckf', '/openvins_bag_probe'))
                if args.camera_topic in subscriptions and args.imu_topic in subscriptions:
                    record['subscriptions'] = subscriptions
                    break
            else:
                raise RuntimeError('estimator input subscriptions not discovered')
            # Recorded original headers remain untouched; /clock is generated by rosbag2.
            command = ['ros2', 'bag', 'play', str(bag), '--rate', str(args.rate),
                       '--clock', '100', '--delay', '2', '--read-ahead-queue-size', '1000']
            record['player_command'] = command
            player = subprocess.Popen(command, stdout=player_log, stderr=subprocess.STDOUT)
            deadline = time.monotonic() + 300
            while player.poll() is None:
                if estimator.poll() is not None:
                    raise RuntimeError('estimator exited during replay')
                if time.monotonic() >= deadline:
                    raise RuntimeError('replay timed out')
                rclpy.spin_once(node, timeout_sec=.02)
            record['player_returncode'] = player.returncode
            if player.returncode:
                raise RuntimeError('rosbag replay failed')
            until = time.monotonic() + 2
            while time.monotonic() < until:
                rclpy.spin_once(node, timeout_sec=.02)
            estimator.send_signal(signal.SIGINT)
            record['estimator_returncode'] = estimator.wait(timeout=15)
            if estimator.returncode:
                raise RuntimeError('estimator shutdown failed')
    except Exception as exc:
        record['error'] = repr(exc)
    finally:
        for process in [player, estimator]:
            if process is not None and process.poll() is None:
                record['forced'] = True
                process.terminate()
                try:
                    process.wait(timeout=3)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait(timeout=3)
        if node is not None:
            node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    with (out / 'poses.jsonl').open('w') as stream:
        for sample in samples:
            stream.write(json.dumps(sample) + '\n')
    checks = dict(sufficient_states=len(samples) >= 100)
    if samples:
        checks['finite_states'] = all(
            math.isfinite(v) for s in samples
            for k in ['position', 'quaternion', 'covariance'] for v in s[k])
        checks['source_monotonic'] = all(
            b['stamp_ns'] > a['stamp_ns'] for a, b in zip(samples, samples[1:]))
        checks['normalized_quaternions'] = all(
            abs(sum(v*v for v in s['quaternion']) - 1) < 1e-5 for s in samples)
        record['source_duration'] = (samples[-1]['stamp_ns'] - samples[0]['stamp_ns']) * 1e-9
        displacement = max(math.dist(s['position'], samples[0]['position']) for s in samples)
        record['observed_displacement'] = displacement
        checks['nonstatic_output'] = displacement > .2
        checks['continuous_run'] = record['source_duration'] > 10
    record['state_count'] = len(samples)
    record['checks'] = checks
    record['passed'] = all(checks.values()) and record['error'] is None and not record['forced']
    record['logs_sha256'] = {
        p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in out.glob('*.log')}
    (out / 'summary.json').write_text(json.dumps(record, indent=2) + '\n')
    fields = ['passed', 'error', 'state_count', 'checks']
    print(json.dumps({k: record[k] for k in fields}, indent=2))
    return 0 if record['passed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
