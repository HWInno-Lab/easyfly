"""One-time deployment and portable private ground-connection bundles."""

from pathlib import Path
import subprocess
import time

from ament_index_python.packages import get_package_prefix

from .remote_profiles import private_json
from .remote_service import atomic, private_directory


def client_settings(path):
    """Resolve credentials relative to the selected portable connection file."""
    path = Path(path).absolute()
    result = private_json(path)
    for key in ("ca_file", "token_file"):
        if result.get(key) and not Path(result[key]).is_absolute():
            result[key] = str(path.parent / result[key])
    return result


def export_client(root, target):
    """Export operator identity and public CA; never export the server private key."""
    root, target = Path(root), Path(target)
    server = private_json(root / "server.json")
    client = private_json(root / "client.json")
    host = server.get("advertised_host", "127.0.0.1")
    if host in ("localhost", "127.0.0.1"):
        raise ValueError("当前只允许本机管理；首次部署时请填写地面端可访问的机载地址")
    private_directory(target)
    if any(target.iterdir()):
        raise ValueError("请选择新的空连接包目录，未覆盖已有内容")
    for key, name in (("certificate", "platform-ca.pem"), ("token_file", "operator.token")):
        with (target / name).open("xb") as stream:
            stream.write(Path(server[key]).read_bytes())
        (target / name).chmod(0o600)
    client.update(
        url="https://" + host + ":" + str(server["port"]),
        ca_file="platform-ca.pem",
        token_file="operator.token",
    )
    atomic(target / "client.json", client)
    return str(target / "client.json")


def unit_text(config_path, executable):
    """Prevent service-manager escalation against active aircraft modules."""

    def quote(value):
        value = str(value)
        if any(ord(character) < 32 for character in value):
            raise ValueError("invalid systemd path")
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%") + '"'

    return (
        "# Generated by EasyFly onboard deployment\n"
        "[Unit]\nDescription=EasyFly onboard platform\nAfter=network-online.target\n\n"
        "[Service]\nType=simple\nExecStart="
        + quote(executable)
        + " --config "
        + quote(config_path)
        + "\nKillMode=process\nSendSIGKILL=no\nTimeoutStopSec=infinity\nRestart=no\n"
        "Environment=PYTHONNOUSERSITE=1\n\n[Install]\nWantedBy=default.target\n"
    )


def install_user_service(root, client, snapshot, unit_directory=None):
    """Enable the daemon only after its previous instance owns no live work."""
    root = Path(root)
    if snapshot["state"]["phase"] not in ("stopped", "failed"):
        raise ValueError("请先正常停止平台，再启用开机服务")
    executable = (
        Path(get_package_prefix("easyfly_connection_manager"))
        / "lib/easyfly_connection_manager/easyfly_onboard_service"
    )
    config_path = root / "server.json"
    settings = private_json(config_path)
    directory = Path(unit_directory or (Path.home() / ".config/systemd/user"))
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    unit = directory / ("easyfly-onboard-" + settings["server_id"][:12] + ".service")
    content = unit_text(config_path, executable)
    if unit.exists() and (unit.is_symlink() or unit.read_text() != content):
        raise ValueError("已有不同的同名服务文件，未覆盖")
    if not unit.exists():
        with unit.open("x") as stream:
            stream.write(content)
        unit.chmod(0o600)
    response = client.operation(snapshot, "service_exit", {})
    if not response.get("accepted"):
        raise ValueError(response.get("reason", "平台服务未退出"))
    for _ in range(50):
        try:
            client.status()
        except OSError:
            break
        time.sleep(0.1)
    else:
        raise RuntimeError("原平台服务仍在运行，未启动第二套")
    for argv in (
        ["systemctl", "--user", "daemon-reload"],
        ["systemctl", "--user", "enable", "--now", unit.name],
    ):
        result = subprocess.run(argv, capture_output=True, text=True, timeout=15)
        if result.returncode:
            raise RuntimeError("系统服务未启用：" + result.stderr[-2048:])
    return dict(accepted=True, phase="service_installed", unit=str(unit))
